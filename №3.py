import math
print("Задание 3. Наименьший радиус круга для треугольника")
try:
    a = float(input("Введите сторону a: "))
    b = float(input("Введите сторону b: "))
    c = float(input("Введите сторону c: "))
except ValueError:
    print("Ошибка: введено не число!")
else:
    # Проверка на положительность сторон
    if a <= 0 or b <= 0 or c <= 0:
        print("Ошибка: стороны треугольника должны быть положительными числами.")
    # Проверка неравенства треугольника
    elif (a + b <= c) or (a + c <= b) or (b + c <= a):
        print("Ошибка: треугольник с такими сторонами не существует "
              "(не выполняется неравенство треугольника).")
    else:
        # Вычисление полупериметра
        p = (a + b + c) / 2

        # Вычисление площади по формуле Герона
        S = math.sqrt(p * (p - a) * (p - b) * (p - c))

        # Вычисление радиуса описанной окружности
        R = (a * b * c) / (4 * S)

        print(f"\nПолупериметр: p = {p:.4f}")
        print(f"Площадь треугольника: S = {S:.4f}")
        print(f"Наименьший радиус круга: R = {R:.4f}")