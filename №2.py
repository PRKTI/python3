print("Задание 2. Принадлежность точки области")
print("Область: верхний полукруг x² + y² ≤ 9, y ≥ 0\n")

try:
    x = float(input("Введите координату x: "))
    y = float(input("Введите координату y: "))
except ValueError:
    print("Ошибка: введено не число!")
else:
    if (x**2 + y**2 <= 9) and (y >= 0):
        print(f"Точка ({x}, {y}) принадлежит заштрихованной области.")
    else:
        print(f"Точка ({x}, {y}) НЕ принадлежит заштрихованной области.")